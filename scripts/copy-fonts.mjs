// Copies the bundled woff2 fonts used by the UI into src/renderer/fonts and writes fonts.css.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'src/renderer/fonts');
fs.mkdirSync(out, { recursive: true });
const wanted = [
  ['inter', ['400', '500', '600', '700'], ['normal']],
  ['stix-two-text', ['400', '500'], ['normal', 'italic']],
  ['jetbrains-mono', ['400'], ['normal']],
];
const subsets = ['latin', 'latin-ext', 'greek'];
let css = '/* Generated by scripts/copy-fonts.mjs from @fontsource packages (SIL Open Font License). */\n';
for (const [pkg, weights, styles] of wanted) {
  for (const w of weights) for (const s of styles) {
    const file = path.join(root, 'node_modules/@fontsource', pkg, s === 'italic' ? `${w}-italic.css` : `${w}.css`);
    const src = fs.readFileSync(file, 'utf8');
    for (const block of src.split('/*').slice(1)) {
      const body = block.slice(block.indexOf('@font-face'));
      const m = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body);
      if (!m) continue;
      const sub = m[1].slice(pkg.length + 1).replace(/-\d+-(normal|italic)\.woff2$/, '');
      if (!subsets.includes(sub)) continue;
      fs.copyFileSync(path.join(root, 'node_modules/@fontsource', pkg, 'files', m[1]), path.join(out, m[1]));
      css += body.replace(/url\(\.\/files\//g, 'url(./').replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '') + '\n';
    }
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
console.log('fonts copied:', fs.readdirSync(out).length - 1);
